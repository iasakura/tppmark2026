#!/usr/bin/env python3
"""Turn the published task list of "Othello is Solved" and the hint strings
written by tools/top8.cpp into Lean files.

  top8_to_lean.py tasklist.csv black.hint white.hint Table.lean Hints.lean

Table.lean contains the rows of empty50_tasklist_edax_knowledge.csv verbatim
(board, score, alpha, beta; the column `count` is dropped).  Hints.lean
contains the two hint strings (untrusted data).
"""
import re
import sys


def lean_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 6:
        sys.exit(__doc__)
    csv_path, black_hint, white_hint, table_out, hints_out = sys.argv[1:]
    rows = []
    for line in open(csv_path, encoding='utf-8'):
        m = re.fullmatch(r'([-OX]{64}) X;,([0-9]+),(-?[0-9]{1,2}),(-?[0-9]{1,2}),(-?[0-9]{1,2})', line.strip())
        if m is None:
            continue
        rows.append((m.group(1), int(m.group(3)), int(m.group(4)), int(m.group(5))))
    assert len(rows) == 2587, len(rows)
    with open(table_out, 'w') as f:
        f.write('''/-!
# The table of 2587 positions with 50 empty squares from "Othello is Solved"

This file is data.  It reproduces, row by row, the file
`empty50_tasklist_edax_knowledge.csv` of

  https://github.com/eukaryo/reversi-scripts   (commit 5d045bca, GPL-3.0)

which accompanies H. Takizawa, "Othello is Solved" (arXiv:2310.19387).  Each
row is a position with 50 empty squares and Black (`X`) to move, written as
64 characters (A1, B1, …, H1, A2, …, H8; `X` black, `O` white, `-` empty),
followed by the three numbers `score`, `alpha`, `beta` of that file (its
column `count` is omitted).  Their meaning is explained in
`Othello/Eight.lean`.

Generated by `tools/top8_to_lean.py`.
-/

namespace Othello

/-- A row of the table. -/
structure Entry where
  board : String
  score : Int
  alpha : Int
  beta : Int

set_option maxRecDepth 100000 in
/-- The 2587 rows of `empty50_tasklist_edax_knowledge.csv`. -/
def takizawaTable : List Entry := [
''')
        f.write(',\n'.join(f'  ⟨"{b}", {s}, {a}, {be}⟩' for b, s, a, be in rows))
        f.write(''']

end Othello
''')
    hb = open(black_hint).read().strip()
    hw = open(white_hint).read().strip()
    with open(hints_out, 'w') as f:
        f.write('''/-!
# Hints for the search of the first ten plies of 8 × 8 Othello

Generated by `tools/top8.cpp` and `tools/top8_to_lean.py`.  This is untrusted
data: hints only tell the verified search which moves to try first.
-/

namespace Othello

/-- Hints for "Black secures a draw" (down to the positions of the table). -/
def hintBlack8 : String :=
  %s

/-- Hints for "White secures a draw" (down to the positions of the table). -/
def hintWhite8 : String :=
  %s

end Othello
''' % (lean_string(hb), lean_string(hw)))
    print(f'{len(rows)} rows, hints: {len(hb)} and {len(hw)} characters')


if __name__ == '__main__':
    main()
