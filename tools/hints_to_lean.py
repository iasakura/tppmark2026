#!/usr/bin/env python3
"""Turn the hint files written by tools/gen.cpp into Othello/Six/Hints.lean.

The hint strings are replayed on a 6x6 board in order to find out which hint
nodes belong to "and" nodes of the search (all moves of the opponent have to be
answered).  Those with at least EP empty squares are marked with braces, which
asks the verified search to examine their moves in parallel.

Hints are untrusted data: they only influence the order in which the verified
search tries moves, never its result.
"""
import sys

N = 6
MASK = 0
for y in range(N):
    for x in range(N):
        MASK |= 1 << (8 * y + x)
DIRS = [1, 7, 8, 9, -1, -7, -8, -9]


def shift(b, d):
    return (b << d) & 0xFFFFFFFFFFFFFFFF if d > 0 else b >> (-d)


def flips(me, opp, m):
    f = 0
    for d in DIRS:
        x = shift(m, d) & opp
        g = 0
        while x:
            g |= x
            nx = shift(x, d)
            if nx & me:
                f |= g
                break
            x = nx & opp
    return f


def mobility(me, opp):
    empty = MASK & ~(me | opp)
    mv = 0
    for d in DIRS:
        x = shift(me, d) & opp
        for _ in range(N - 3):
            x |= shift(x, d) & opp
        mv |= shift(x, d)
    return mv & empty


def parse(s, pos):
    """Parse a hint node starting at s[pos] == '('.  Returns (children, pos')."""
    assert s[pos] == '('
    pos += 1
    children = []
    while s[pos] != ')':
        c = s[pos]
        pos += 1
        sub = None
        if s[pos] == '(':
            sub, pos = parse(s, pos)
        children.append((c, sub))
    return children, pos + 1


def emit(node, kind, me, opp, ep, stats):
    """kind 'M': the player to move secures the margin (an "or" node);
       kind 'O': the other player does (an "and" node)."""
    if node is None:
        return ''
    mv = mobility(me, opp)
    if mv == 0:
        if mobility(opp, me) == 0:
            assert not node
            return '()'
        return emit(node, 'O' if kind == 'M' else 'M', opp, me, ep, stats)
    empties = bin(MASK & ~(me | opp)).count('1')
    par = kind == 'O' and empties >= ep and len(node) > 1
    out = '{' if par else '('
    if par:
        stats['par'] += 1
    for c, sub in node:
        sq = ord(c) - 48
        m = 1 << sq
        assert mv & m, 'hinted move is not legal'
        f = flips(me, opp, m)
        out += c
        out += emit(sub, 'O' if kind == 'M' else 'M', opp ^ f, me | m | f, ep, stats)
    out += '}' if par else ')'
    return out


def lean_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 5:
        sys.exit('usage: hints_to_lean.py black.hint white.hint EP out.lean')
    ep = int(sys.argv[3])
    h = N // 2
    white = (1 << (8 * (h - 1) + (h - 1))) | (1 << (8 * h + h))
    black = (1 << (8 * (h - 1) + h)) | (1 << (8 * h + (h - 1)))
    res = []
    for path, kind in ((sys.argv[1], 'M'), (sys.argv[2], 'O')):
        s = open(path).read().strip()
        node, pos = parse(s, 0)
        assert pos == len(s)
        stats = {'par': 0}
        t = emit(node, kind, black, white, ep, stats)
        print(f'{path}: {len(s)} characters, {stats["par"]} parallel nodes', file=sys.stderr)
        res.append(t)
    with open(sys.argv[4], 'w') as f:
        f.write('''/-!
# Hints for the 6 × 6 search

Generated by `tools/gen.cpp` and `tools/hints_to_lean.py`.  This is untrusted
data: hints only influence the order in which the verified search tries moves.
-/

namespace Othello

/-- Hints for "Black secures a margin of at least -4". -/
def hintBlack6 : String :=
  %s

/-- Hints for "White secures a margin of at least 4". -/
def hintWhite6 : String :=
  %s

end Othello
''' % (lean_string(res[0]), lean_string(res[1])))


if __name__ == '__main__':
    main()
